#!/usr/bin/env python3
"""Render shared instructions and safely install or restore agent entrypoints."""
import argparse
import difflib
import hashlib
import json
import os
from pathlib import Path
import re
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
STATE = '.agent-config-instructions.json'


def digest(text):
    return hashlib.sha256(text.encode('utf-8')).hexdigest() if text is not None else None


def read_source(root, relative):
    path = (root / relative).resolve()
    if not path.is_relative_to(root.resolve()) or not path.is_file():
        raise ValueError(f'Missing or external instruction source: {relative}')
    text = path.read_text(encoding='utf-8').strip()
    if not text:
        raise ValueError(f'Empty instruction source: {relative}')
    return text


def load_scopes(root):
    rules = json.loads((root / 'instructions/scopes.json').read_text())
    if not isinstance(rules, dict) or not rules:
        raise ValueError('scopes.json must contain named rules')
    for name, rule in rules.items():
        if not re.fullmatch('[a-z0-9]+(?:-[a-z0-9]+)*', name) or not isinstance(rule, dict):
            raise ValueError(f'Invalid rule: {name}')
        if set(rule) not in ({'source', 'paths'}, {'source', 'when'}):
            raise ValueError(f'{name}: specify source and exactly one of paths or when')
        read_source(root, rule['source'])
        if 'paths' in rule:
            if not isinstance(rule['paths'], list) or not rule['paths']:
                raise ValueError(f'{name}: paths must be a nonempty list')
            for pattern in rule['paths']:
                if not isinstance(pattern, str) or not re.fullmatch(r'\*\*/\*\.[a-z]+', pattern):
                    raise ValueError(f'{name}: only extension globs (**/*.ext) are supported')
        elif not isinstance(rule['when'], str) or not rule['when'].strip():
            raise ValueError(f'{name}: when must be nonempty text')
    return rules


def render(root, agent):
    root = root.resolve()
    common = read_source(root, 'instructions/global.md')
    adapter = read_source(root, f'adapters/{agent}.md')
    notice = f'<!-- Generated by agent-config from {root}; edit the shared sources, then reinstall. -->\n'
    routing = ['## Shared rules to read when applicable']
    outputs = {}
    for name, rule in load_scopes(root).items():
        body = read_source(root, rule['source'])
        source = root / rule['source']
        if 'paths' in rule and agent == 'claude':
            header = '---\npaths: ' + json.dumps(rule['paths']) + '\n---\n\n'
            outputs[f'rules/agent-config-{name}.md'] = header + notice + '\n' + body + '\n'
        else:
            condition = rule.get('when') or ('Working on files matching ' + ', '.join(f'`{p}`' for p in rule['paths']))
            routing.append(f'- {condition}: read `{source}`. Apply only within that scope.')
    entry = 'CLAUDE.md' if agent == 'claude' else 'AGENTS.md'
    outputs[entry] = notice + '\n' + common + '\n\n' + adapter + '\n\n' + '\n'.join(routing) + '\n'
    return outputs


def render_sources(sources, agent):
    if not sources:
        raise ValueError('No instruction sources specified')
    entry = 'CLAUDE.md' if agent == 'claude' else 'AGENTS.md'
    sections = []
    outputs = {}
    for name, root in sources.items():
        if not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', name):
            raise ValueError(f'Invalid source name: {name}')
        root = root.resolve()
        notice = f'<!-- Generated by agent-config from {root}; edit the shared sources, then reinstall. -->\n'
        common = read_source(root, 'instructions/global.md')
        sections.append(notice + '\n' + common)
        adapter = root / 'adapters' / f'{agent}.md'
        if adapter.exists():
            sections.append(read_source(root, f'adapters/{agent}.md'))
        routing = []
        for rule_name, rule in load_scopes(root).items():
            source = root / rule['source']
            body = read_source(root, rule['source'])
            if 'paths' in rule and agent == 'claude':
                relative = f'rules/agent-config-{name}-{rule_name}.md'
                if relative in outputs:
                    raise ValueError(f'Instruction rule collision: {relative}')
                header = '---\npaths: ' + json.dumps(rule['paths']) + '\n---\n\n'
                outputs[relative] = header + notice + '\n' + body + '\n'
            else:
                condition = rule.get('when') or ('Working on files matching ' + ', '.join(f'`{p}`' for p in rule['paths']))
                routing.append(f'- {condition}: read `{source}`. Apply only within that scope.')
        if routing:
            sections.append('## Shared rules to read when applicable\n' + '\n'.join(routing))
    outputs[entry] = '\n\n'.join(sections) + '\n'
    return outputs


def safe_target(home, relative):
    if relative not in ('CLAUDE.md', 'AGENTS.md', STATE) and not re.fullmatch(r'rules/agent-config-[a-z0-9-]+\.md', relative):
        raise ValueError(f'Unexpected managed path: {relative}')
    target = home / relative
    if target.is_symlink() or not target.resolve().is_relative_to(home.resolve()):
        raise ValueError(f'Refusing to replace symlink or external target: {target}')
    return target


def snapshot(path):
    if not path.exists():
        return None
    return {'text': path.read_text(encoding='utf-8'), 'mode': path.stat().st_mode & 0o777}


def write_snapshot(path, value):
    if value is None:
        path.unlink(missing_ok=True)
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp = tempfile.mkstemp(prefix='.agent-config-', dir=path.parent)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as stream:
            stream.write(value['text'])
        os.chmod(temp, value['mode'])
        os.replace(temp, path)
    finally:
        Path(temp).unlink(missing_ok=True)


def prepare(home, outputs, restore=False):
    state_path = safe_target(home, STATE)
    old_state = snapshot(state_path)
    state = json.loads(old_state['text']) if old_state else {'version': 1, 'files': {}}
    if state.get('version') != 1 or not isinstance(state.get('files'), dict):
        raise ValueError(f'Unsupported installation state: {state_path}')
    managed = state['files']
    desired = {} if restore else outputs
    changes = []
    new_files = {}
    for relative in sorted(set(managed) | set(desired)):
        path = safe_target(home, relative)
        before = snapshot(path)
        old = managed.get(relative)
        current = before['text'] if before else None
        if old and digest(current) != old['installed_sha256']:
            raise ValueError(f'Locally modified or missing managed file; preserve edits before reinstalling: {path}')
        if relative in desired:
            after = {'text': desired[relative], 'mode': before['mode'] if before else 0o600}
            original = old['original'] if old else before
            new_files[relative] = {'installed_sha256': digest(after['text']), 'original': original}
        else:
            after = old['original']
        if before != after:
            changes.append((path, before, after))
    if restore:
        new_state = None
    else:
        new_state = {'text': json.dumps({'version': 1, 'files': new_files}, indent=2) + '\n', 'mode': 0o600}
    if old_state != new_state:
        changes.append((state_path, old_state, new_state))
    return changes


def apply(changes):
    written = []
    try:
        for path, before, after in changes:
            if snapshot(path) != before:
                raise ValueError(f'File changed since preflight: {path}')
            write_snapshot(path, after)
            written.append((path, before))
    except (OSError, ValueError):
        for path, before in reversed(written):
            write_snapshot(path, before)
        raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--agent', choices=['claude', 'codex', 'all'], default='all')
    parser.add_argument('--claude-home', type=Path, default=Path(os.environ.get('CLAUDE_CONFIG_DIR', Path.home() / '.claude')))
    parser.add_argument('--codex-home', type=Path, default=Path(os.environ.get('CODEX_HOME', Path.home() / '.codex')))
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--apply', action='store_true', help='install generated instructions')
    mode.add_argument('--restore', action='store_true', help='restore the files saved before first installation')
    mode.add_argument('--check', action='store_true', help='exit nonzero if installation differs')
    args = parser.parse_args()
    changes = []
    for agent in ('claude', 'codex') if args.agent == 'all' else (args.agent,):
        home = getattr(args, f'{agent}_home').expanduser().resolve()
        override = home / 'AGENTS.override.md'
        if agent == 'codex' and override.is_file() and override.read_text().strip():
            print(f'WARNING: {override} masks AGENTS.md; it will not be modified.', file=sys.stderr)
            if not args.restore:
                raise ValueError('Resolve the active Codex global override before installation')
        changes.extend(prepare(home, render(ROOT, agent), args.restore))
    if len({path for path, _, _ in changes}) != len(changes):
        raise ValueError('Agent home directories must be distinct')
    if args.apply or args.restore:
        apply(changes)
        print(f'{len(changes)} files updated; original contents are saved in {STATE} in each agent home.')
    elif args.check:
        if changes:
            for path, _, _ in changes:
                print(f'Out of date: {path}')
            return 1
        print('Installed instructions match shared sources')
    else:
        for path, before, after in changes:
            if path.name == STATE:
                continue
            print(''.join(difflib.unified_diff(
                (before['text'] if before else '').splitlines(True),
                (after['text'] if after else '').splitlines(True),
                fromfile=str(path), tofile=str(path) + ' (generated)')), end='')
        if not changes:
            print('No changes')
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print(f'Error: {exc}', file=sys.stderr)
        sys.exit(1)
